<?php
/** Shared helpers for the AeroHangar management system. This folder must not be web-readable. */
declare(strict_types=1);

const AH_FILES = ['bulletins', 'contacts', 'types', 'news', 'examiners'];
const AH_KEEP_BACKUPS = 40;

define('AH_PRIVATE', __DIR__);
if (!defined('AH_DATA')) define('AH_DATA', __DIR__ . '/../public/data');
/** Everything the system writes (config, backups, log) – keep it, back it up; mount it as a volume in Docker. */
define('AH_STATE', AH_PRIVATE . '/state');
if (!is_dir(AH_STATE)) @mkdir(AH_STATE, 0700, true);
define('AH_CONFIG', AH_STATE . '/config.php');
define('AH_BACKUPS', AH_STATE . '/backups');
define('AH_LOG', AH_STATE . '/audit.log');

if (session_status() !== PHP_SESSION_ACTIVE && PHP_SAPI !== 'cli') {
    session_name('ahsess');
    session_set_cookie_params([
        'lifetime' => 0, 'path' => '/', 'httponly' => true, 'samesite' => 'Strict',
        'secure' => (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https'),
    ]);
    session_start();
}

function ah_config(bool $reload = false): array
{
    static $c = null;
    if ($c === null || $reload) {
        if (function_exists('opcache_invalidate')) @opcache_invalidate(AH_CONFIG, true);
        $c = is_file(AH_CONFIG) ? (require AH_CONFIG) : [];
    }
    return $c;
}

function ah_configured(): bool
{
    return !empty(ah_config()['users']);
}

function ah_public_base(): string
{
    return (string)(ah_config()['publicBase'] ?? '');
}

function ah_save_config(array $c): void
{
    ah_write_atomic(AH_CONFIG, "<?php\n// Generated by AeroHangar – edit with care.\nreturn " . var_export($c, true) . ";\n");
    @chmod(AH_CONFIG, 0600);
    ah_config(true);
}

function ah_find_user(string $login): ?array
{
    foreach (ah_config()['users'] ?? [] as $u) {
        if (strcasecmp($u['login'], $login) === 0) return $u;
    }
    return null;
}

function ah_list_users(): array
{
    return array_map(fn($u) => ['login' => $u['login'], 'role' => $u['role']], ah_config()['users'] ?? []);
}

function ah_save_user(string $login, string $password, string $role, bool $delete, string $by): ?string
{
    $login = trim($login);
    if (!preg_match('/^[A-Za-z0-9._@-]{3,40}$/', $login)) return 'login: 3–40 letters, digits, . _ @ -';
    if (!in_array($role, ['admin', 'editor', 'viewer'], true)) return 'bad role';
    $c = ah_config();
    $users = $c['users'] ?? [];
    $idx = null;
    foreach ($users as $i => $u) if (strcasecmp($u['login'], $login) === 0) $idx = $i;
    if ($delete) {
        if ($idx === null) return 'no such user';
        if (strcasecmp($login, $by) === 0) return 'you cannot delete yourself';
        array_splice($users, $idx, 1);
    } else {
        if ($idx === null && strlen($password) < 10) return 'password: at least 10 characters';
        $hash = $password !== '' ? password_hash($password, PASSWORD_DEFAULT) : $users[$idx]['hash'];
        $entry = ['login' => $login, 'role' => $role, 'hash' => $hash];
        if ($idx === null) $users[] = $entry; else $users[$idx] = $entry;
    }
    if (!array_filter($users, fn($u) => $u['role'] === 'admin')) return 'at least one admin must remain';
    $c['users'] = array_values($users);
    ah_save_config($c);
    ah_log($by, ($delete ? 'delete' : 'save') . " user $login ($role)");
    return null;
}

// ---------------------------------------------------------------- login throttling

function ah_attempts_file(): string
{
    return AH_STATE . '/attempts_' . sha1($_SERVER['REMOTE_ADDR'] ?? 'cli') . '.json';
}

function ah_login_blocked(): bool
{
    $f = ah_attempts_file();
    if (!is_file($f)) return false;
    $a = json_decode((string)file_get_contents($f), true) ?: [];
    $recent = array_filter($a, fn($t) => $t > time() - 900);
    return count($recent) >= 8;
}

function ah_login_failed(): void
{
    $f = ah_attempts_file();
    $a = is_file($f) ? (json_decode((string)file_get_contents($f), true) ?: []) : [];
    $a = array_values(array_filter($a, fn($t) => $t > time() - 900));
    $a[] = time();
    file_put_contents($f, json_encode($a));
}

// ---------------------------------------------------------------- data files

function ah_data_path(string $f): string
{
    return AH_DATA . '/' . $f . '.json';
}

function ah_write_atomic(string $path, string $content): void
{
    $dir = dirname($path);
    if (!is_dir($dir)) mkdir($dir, 0755, true);
    $tmp = tempnam($dir, '.tmp');
    if ($tmp === false || file_put_contents($tmp, $content, LOCK_EX) === false) {
        throw new RuntimeException("cannot write $path – check folder permissions");
    }
    @chmod($tmp, 0644);
    rename($tmp, $path);
}

function ah_backup(string $f, string $content): void
{
    if ($content === '') return;
    if (!is_dir(AH_BACKUPS)) mkdir(AH_BACKUPS, 0700, true);
    file_put_contents(AH_BACKUPS . '/' . $f . '-' . date('Ymd-His') . '-' . substr(sha1($content), 0, 6) . '.json', $content);
    $all = glob(AH_BACKUPS . '/' . $f . '-*.json') ?: [];
    rsort($all);
    foreach (array_slice($all, AH_KEEP_BACKUPS) as $old) @unlink($old);
}

function ah_list_backups(): array
{
    $all = glob(AH_BACKUPS . '/*.json') ?: [];
    rsort($all);
    return array_map(fn($p) => ['name' => basename($p), 'size' => filesize($p)], array_slice($all, 0, 200));
}

function ah_restore(string $name, string $by): bool
{
    if (!preg_match('/^(' . implode('|', AH_FILES) . ')-\d{8}-\d{6}-[0-9a-f]{6}\.json$/', $name, $m)) return false;
    $src = AH_BACKUPS . '/' . $name;
    if (!is_file($src)) return false;
    ah_backup($m[1], ah_read_editable($m[1]));
    $restored = json_decode((string)file_get_contents($src), true);
    if (!is_array($restored)) return false;
    ah_write_editable($m[1], $restored);
    ah_log($by, "restore $name");
    return true;
}

/** Light structural checks so a typo in the panel cannot break the apps. */
function ah_validate(string $f, $d): ?string
{
    if (!is_array($d)) return 'data must be JSON';
    switch ($f) {
        case 'bulletins':
            if (!isset($d['bulletins']) || !is_array($d['bulletins'])) return 'missing "bulletins"';
            $ids = [];
            foreach ($d['bulletins'] as $b) {
                foreach (['id', 'date', 'title', 'groups', 'kind'] as $k) if (!isset($b[$k])) return "bulletin without $k";
                if (!preg_match('/^\d{4}-\d{2}-\d{2}$/', (string)$b['date'])) return "bad date in {$b['id']}";
                if (isset($ids[$b['id']])) return "duplicate bulletin {$b['id']}";
                $ids[$b['id']] = 1;
            }
            return null;
        case 'contacts':
        case 'examiners':
            if (!isset($d['contacts']) || !is_array($d['contacts'])) return 'missing "contacts"';
            $ids = [];
            foreach ($d['contacts'] as $c) {
                if (empty($c['id']) || empty($c['name']) || empty($c['kind'])) return 'contact without id/name/kind';
                if (isset($ids[$c['id']])) return "duplicate contact {$c['id']}";
                $ids[$c['id']] = 1;
            }
            return null;
        case 'types':
            if (!array_is_list($d) || count($d) < 2) return 'types must be a list';
            $ids = [];
            foreach ($d as $t) {
                foreach (['id', 'name', 'family', 'category', 'bulletinGroups', 'speeds', 'manual', 'tasks'] as $k) if (!isset($t[$k])) return "type without $k";
                if (!in_array($t['category'], ['EASA', 'UL'], true)) return "bad category in {$t['id']}";
                if (isset($ids[$t['id']])) return "duplicate type {$t['id']}";
                $ids[$t['id']] = 1;
            }
            return null;
        case 'news':
            if (!isset($d['messages']) || !is_array($d['messages'])) return 'missing "messages"';
            foreach ($d['messages'] as $n) if (empty($n['id']) || empty($n['title'])) return 'message without id/title';
            return null;
    }
    return 'unknown file';
}

// ---------------------------------------------------------------- audit log

function ah_log(string $who, string $what): void
{
    @file_put_contents(AH_LOG, date('c') . "\t" . $who . "\t" . str_replace(["\n", "\t"], ' ', $what) . "\n", FILE_APPEND | LOCK_EX);
}

function ah_read_log(int $n): array
{
    if (!is_file(AH_LOG)) return [];
    $lines = file(AH_LOG, FILE_IGNORE_NEW_LINES) ?: [];
    return array_reverse(array_slice($lines, -$n));
}

// ---------------------------------------------------------------- working copy vs. published file
// Contacts and examiners: the panel edits a working copy in private/state (all entries, incl. unpublished);
// the public file in data/ contains only entries with publish !== false. Other files are edited directly.
const AH_MASTERED = ['contacts', 'examiners'];

function ah_master_path(string $f): string
{
    return AH_STATE . '/master_' . $f . '.json';
}

/** Raw JSON of what the panel edits. */
function ah_read_editable(string $f): string
{
    if (in_array($f, AH_MASTERED, true) && is_file(ah_master_path($f))) return (string)file_get_contents(ah_master_path($f));
    $p = ah_data_path($f);
    return is_file($p) ? (string)file_get_contents($p) : '';
}

function ah_json(array $d): string
{
    return json_encode($d, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT) . "\n";
}

/** Writes the editable copy and (for contacts/examiners) regenerates the published file. Returns new rev. */
function ah_write_editable(string $f, array $d): string
{
    $json = ah_json($d);
    if (in_array($f, AH_MASTERED, true)) {
        ah_write_atomic(ah_master_path($f), $json);
        $pub = $d;
        unset($pub['publishNew']);
        $pub['contacts'] = array_values(array_map(function ($c) { unset($c['publish']); return $c; },
            array_filter($d['contacts'] ?? [], fn($c) => ($c['publish'] ?? true) !== false)));
        ah_write_atomic(ah_data_path($f), ah_json($pub));
    } else {
        ah_write_atomic(ah_data_path($f), $json);
    }
    return sha1($json);
}

/** Bot / GitHub import of official ULC entries into a mastered file (keeps the owner's publish choice). */
function ah_merge_official(string $target, array $prefixes, array $incoming, string $who): array
{
    $raw = ah_read_editable($target);
    $feed = $raw ? json_decode($raw, true) : ['version' => 0, 'updated' => '', 'contacts' => []];
    $default = $feed['publishNew'] ?? ($target === 'contacts');
    $old = [];
    foreach ($feed['contacts'] as $c) $old[$c['id']] = $c;
    $keep = array_values(array_filter($feed['contacts'], fn($c) => !array_filter($prefixes, fn($p) => str_starts_with($c['id'], $p))));
    $ids = array_flip(array_column($keep, 'id'));
    $added = 0;
    foreach ($incoming as $c) {
        if (isset($ids[$c['id']])) continue;
        $c['publish'] = isset($old[$c['id']]) ? ($old[$c['id']]['publish'] ?? true) : $default;
        if (!isset($old[$c['id']])) $added++;
        $keep[] = $c;
        $ids[$c['id']] = 1;
    }
    $feed['contacts'] = $keep;
    $feed['version'] = ($feed['version'] ?? 0) + 1;
    $feed['updated'] = date('Y-m-d');
    ah_backup($target, $raw);
    ah_write_editable($target, $feed);
    ah_log($who, "import $target: " . count($incoming) . " official entries ($added new)");
    return ['imported' => count($incoming), 'new' => $added, 'total' => count($keep)];
}

// ---------------------------------------------------------------- small JSON stores (installs, submissions)

function ah_store_update(string $name, callable $fn)
{
    $path = AH_STATE . '/' . $name . '.json';
    $fh = fopen($path, 'c+');
    flock($fh, LOCK_EX);
    $data = json_decode((string)stream_get_contents($fh), true) ?: [];
    $res = $fn($data);
    ftruncate($fh, 0);
    rewind($fh);
    fwrite($fh, json_encode($data, JSON_UNESCAPED_UNICODE));
    flock($fh, LOCK_UN);
    fclose($fh);
    return $res;
}

function ah_store_read(string $name): array
{
    $path = AH_STATE . '/' . $name . '.json';
    return is_file($path) ? (json_decode((string)file_get_contents($path), true) ?: []) : [];
}

/** Simple per-IP limiter for public endpoints: max $n calls per $sec. */
function ah_rate_ok(string $bucket, int $n, int $sec): bool
{
    $ip = sha1(($_SERVER['REMOTE_ADDR'] ?? '') . 'ah');
    return ah_store_update('rate_' . $bucket, function (&$d) use ($ip, $n, $sec) {
        $now = time();
        foreach ($d as $k => $ts) { $d[$k] = array_values(array_filter($ts, fn($t) => $t > $now - $sec)); if (!$d[$k]) unset($d[$k]); }
        $d[$ip] = $d[$ip] ?? [];
        if (count($d[$ip]) >= $n) return false;
        $d[$ip][] = $now;
        return true;
    });
}

function ah_clean_str($v, int $max): string
{
    return mb_substr(trim(preg_replace('/[\x00-\x1F\x7F]+/u', ' ', (string)$v)), 0, $max);
}
